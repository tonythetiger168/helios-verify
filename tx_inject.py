"""
tx_inject.py — Dynamis tx_record 注入工具 (helios-verify)

最小侵入策略：不逐行改 testbench，而是
  1. 解析 tb 裡的 DUT instantiation（regex，best-effort）
  2. 產生 <proto>_txrecorder.sv：在 posedge clk 時對 interface 訊號呼叫 tx_record
  3. 在 tb 的 endmodule 前插入 2 行：recorder 實例化
  4. 產生 golden：跑一次乾淨模擬，把 tx.jsonl 存為 golden

適用前提（open-ip-portfolio 的 tb 慣例）：
  - DUT 實例化名為 dut（可用 --inst 改）
  - interface 有 clk / rst 名稱（可用 --clk/--rst 改）
  - tb 是可寫檔案（建議先 git commit 再用 --apply）

用法：
  # 只產生 recorder + 預覽 diff（不改檔）
  python tx_inject.py --tb ../open-ip-portfolio/tb/tb_UART.v --dut UART_top --proto UART

  # 確認沒問題後套用
  python tx_inject.py --tb ../open-ip-portfolio/tb/tb_UART.v --dut UART_top --proto UART --apply

  # 產生 golden（先跑乾淨模擬）
  python tx_inject.py --tb ... --proto UART --make-golden
"""

from __future__ import annotations

import argparse
import difflib
import re
import shutil
import subprocess
import sys
from pathlib import Path


# ---------- tb 解析（best-effort regex） ----------

def parse_dut_instantiation(tb_text: str, dut: str, inst: str = "dut") -> dict:
    """找 `DUT inst ( .port(sig), ... );`，回傳 {port: signal}。"""
    pat = re.compile(
        rf"{re.escape(dut)}\s+{re.escape(inst)}\s*\((.*?)\)\s*;",
        re.DOTALL)
    m = pat.search(tb_text)
    if not m:
        raise SystemExit(f"FATAL: 找不到 {dut} {inst} (...) 實例化，"
                         f"請確認 --dut/--inst 或手動注入")
    body = m.group(1)
    conns = {}
    for pm in re.finditer(r"\.(\w+)\s*\(\s*([^)]+?)\s*\)", body):
        port, sig = pm.group(1), pm.group(2).strip()
        conns[port] = sig.split("[")[0].strip()   # 去掉 bit-select
    return conns


# ---------- recorder 產生 ----------

def gen_recorder(proto: str, dut: str, conns: dict,
                 clk: str = "clk", rst: str = "rst") -> str:
    """產生 recorder 模組：posedge clk 且 rst 無效時記錄所有非 clk/rst 訊號。"""
    if clk not in conns.values():
        raise SystemExit(f"FATAL: tb 裡找不到 clk 訊號（--clk 目前={clk}），"
                         f"連線為 {list(conns.values())}")

    # recorder 的 input = tb 裡的實際訊號名（rst 也要進 port，guard 要用）
    ports = [s for s in conns.values() if s not in (clk, rst)]
    decl = f"    input wire {rst},\n"
    decl += "\n".join(f"    input wire [{31 if 'data' in p or 'addr' in p else 0}:0] {p},"
                      for p in ports)
    decl = decl.rstrip(",")
    args = ",\n        ".join(f".{p}({p})" for p in ports)

    fields = ",".join(f"{p}=%0d" for p in ports)
    fieldvals = ", ".join(p for p in ports)

    return f"""// {proto}_txrecorder.sv — auto-generated by tx_inject.py, review before commit
module {proto}_txrecorder (
    input wire {clk},
{decl}
);
    import "DPI-C" context function void tx_record(
        input string kind, input longint t, input string fields);

    always @(posedge {clk}) begin
        if ({rst} !== 1'b1)   // 跳過 reset 期間的雜訊
            tx_record("{proto}", $time,
                      $sformatf("{fields}", {fieldvals}));
    end
endmodule
"""


def gen_instantiation(proto: str, conns: dict, clk: str, rst: str) -> str:
    ports = [s for s in conns.values() if s not in (clk, rst)]
    args = ",\n        ".join(f".{p}({p})" for p in ports)
    return (f"\n    // --- dynamis tx_record (tx_inject.py) ---\n"
            f"    {proto}_txrecorder u_txrec (\n"
            f"        .{clk}({clk}),\n"
            f"        .{rst}({rst}),\n"
            f"        {args}\n"
            f"    );\n")


# ---------- tb 注入 ----------

def inject(tb_path: Path, snippet: str, apply: bool) -> None:
    text = tb_path.read_text()
    if "u_txrec" in text:
        print("已注入過，跳過"); return
    m = list(re.finditer(r"\bendmodule\b", text))
    if not m:
        raise SystemExit("FATAL: tb 裡找不到 endmodule")
    new = text[:m[-1].start()] + snippet + text[m[-1].start():]
    if apply:
        tb_path.write_text(new)
        print(f"已寫入 {tb_path}（recorder 實例化 + 前註解）")
    else:
        diff = difflib.unified_diff(text.splitlines(), new.splitlines(),
                                    lineterm="", n=1)
        print("\n".join(list(diff)[:40]))
        print("\n[預覽] 用 --apply 套用；recorder 模組檔案另存為 "
              f"{tb_path.parent}/<proto>_txrecorder.sv")


# ---------- golden 產生 ----------

def make_golden(workdir: Path, proto: str, makefile: Path | None) -> None:
    tx = workdir / "tx.jsonl"
    if not tx.exists():
        raise SystemExit("FATAL: 找不到 tx.jsonl，請先跑模擬（make sim）")
    gdir = workdir / "golden"
    gdir.mkdir(exist_ok=True)
    shutil.copy(tx, gdir / "tx.jsonl")
    print(f"golden 已建立：{gdir / 'tx.jsonl'}（請 commit 此檔）")


# ---------- main ----------

def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tb", required=True, type=Path)
    ap.add_argument("--dut", required=True)
    ap.add_argument("--proto", required=True)
    ap.add_argument("--inst", default="dut")
    ap.add_argument("--clk", default="clk")
    ap.add_argument("--rst", default="rst")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--make-golden", action="store_true")
    args = ap.parse_args()

    if args.make_golden:
        make_golden(args.tb.parent, args.proto, None)
        return

    text = args.tb.read_text()
    conns = parse_dut_instantiation(text, args.dut, args.inst)
    print(f"解析到 {len(conns)} 個連線：{conns}")

    rec_path = args.tb.parent / f"{args.proto}_txrecorder.sv"
    rec_path.write_text(gen_recorder(args.proto, args.dut, conns,
                                     args.clk, args.rst))
    print(f"recorder 已產生：{rec_path}")

    snippet = gen_instantiation(args.proto, conns, args.clk, args.rst)
    inject(args.tb, snippet, args.apply)

    print("\n下一步：")
    print("  1. 編譯加入 txdpi.cpp：make sim 的 iverilog 指令加 "
          "-I<dynamis>/tx/src <dynamis>/tx/src/txdpi.cpp")
    print(f"  2. 編譯加入 recorder：iverilog 檔案清單加 {rec_path.name}")
    print("  3. 跑模擬產生 tx.jsonl，然後 --make-golden 建立 golden")


if __name__ == "__main__":
    main()
